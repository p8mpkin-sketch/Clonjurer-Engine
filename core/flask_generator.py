def _api_match_src() -> str:
    """core/clone/api_match.py 的函数体(去掉模块文档串与 import): 内嵌进生成的独立工程。"""
    src = (Path(__file__).resolve().parent / "clone" / "api_match.py").read_text(encoding="utf-8")
    body = src.split('"""', 2)[2]
    return "from urllib.parse import parse_qsl\n" + body.replace("import json\nfrom urllib.parse import parse_qsl\n", "").strip()


def _write(path: Path, content: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def build_zip(build_dir: Path, zip_path: Path, top_folder: str):
    """把 build_dir 打包为含 top_folder/ 前缀的 zip。"""
    zip_path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for root, _dirs, files in os.walk(build_dir):
            for fname in sorted(files):
                absolute = Path(root) / fname
                arcname = Path(top_folder) / absolute.relative_to(build_dir)
                zf.write(absolute, str(arcname))
    return zip_path


def generate_project(task_id: int, upstream_origin: str, workspace: Path,
                     pages_map: dict, mock_entries: list, proxy_enabled: bool,
                     tracker_hook: str = "", tracker_cfg: dict = None) -> Path:
    """从任务工作空间组装独立 Flask 工程并打包, 返回 zip 路径。

    tracker_hook 非空时(启用埋点): 所有模板页注入 <script src="/tracker/hook.js">
    (同源相对路径, 手机/局域网/本机均可加载), 生成工程自带
    /tracker/hook.js(引擎, ENDPOINT=相对 /tracker/report)与
    /tracker/report(本地留痕 + 转发平台推送 + 钉钉直推兜底)。
    tracker_cfg: {token, secret, keyword, slots, mask} 构建时烘焙进生成工程。
    """
    build_dir = workspace / "flask_app"
    if build_dir.exists():
        shutil.rmtree(build_dir)
    (build_dir / "templates").mkdir(parents=True, exist_ok=True)

    # 静态资源整树拷贝
    if (workspace / "static").is_dir():
        shutil.copytree(workspace / "static", build_dir / "static", dirs_exist_ok=True)

    # 页面目录与运行时相对路径影子文件(如 apps_resource_supplier/css/*.css):
    # webpack publicPath='' 的懒加载 chunk 按页面目录相对解析, 必须原路径随包
    for entry in workspace.iterdir():
        if entry.is_dir() and entry.name not in ("static", "flask_app", "frames",
                                                 "__pycache__"):
            shutil.copytree(entry, build_dir / entry.name, dirs_exist_ok=True)

    # 页面 HTML -> templates/(支持 frames/frame_N.html 等子路径)
    for route, fname in pages_map.items():
        src = workspace / fname
        if src.is_file():
            dst = build_dir / "templates" / fname
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(src, dst)

    # mock 数据
    _write(build_dir / "mock_data.json", json.dumps(mock_entries, ensure_ascii=False, indent=2))
    # 已知死路径(采集期源站 4xx/5xx 的同源路径): 生成应用对其秒 404, 不回源
    dead_src = workspace / "known_dead.json"
    if dead_src.is_file():
        shutil.copyfile(dead_src, build_dir / "known_dead.json")

    # 引擎内核版: 表单埋点注入已移除(运营功能, 不在本仓库范围)。tracker_hook 恒为空,
    # 生成工程不内嵌任何输入捕获脚本。

    # app.py 令牌替换
    app_src = (
        GENERATED_APP_PY.replace("__API_MATCH_SRC__", _api_match_src())
        .replace("@@PAGES_JSON@@", json.dumps(pages_map, ensure_ascii=False))
        .replace("@@UPSTREAM_ORIGIN@@", upstream_origin)
        .replace("@@PROXY_ENABLED@@", "True" if proxy_enabled else "False")
        .replace("@@TASK_ID@@", str(task_id))
        .replace("@@PROXY_CACHE_MAX@@", str(config.PROXY_CACHE_MAX_BYTES))
        .replace("@@PROXY_CONNECT_TIMEOUT@@", str(config.PROXY_FALLBACK_CONNECT_TIMEOUT))
        .replace("@@PROXY_READ_TIMEOUT@@", str(config.PROXY_FALLBACK_READ_TIMEOUT))
        .replace("@@TRACKER_ENABLED@@",
                 "True" if tracker_hook else "False")
        .replace("@@TRACKER_TASK_ID@@", str(task_id))
        .replace("@@TRACKER_TOKEN@@", json.dumps((tracker_cfg or {}).get("token", ""), ensure_ascii=False))
        .replace("@@TRACKER_SECRET@@", json.dumps((tracker_cfg or {}).get("secret", ""), ensure_ascii=False))
        .replace("@@TRACKER_KEYWORD@@", json.dumps((tracker_cfg or {}).get("keyword", ""), ensure_ascii=False))
        .replace("@@TRACKER_SLOTS@@", json.dumps((tracker_cfg or {}).get("slots", []), ensure_ascii=False))
        .replace("@@TRACKER_MASK@@", "True" if (tracker_cfg or {}).get("mask", True) else "False")
        .replace("@@TRACKER_PLATFORM@@", json.dumps(config.PLATFORM_PUBLIC_URL if tracker_hook else ""))
        .replace("__ENDPOINT__", "/tracker/report")  # 内嵌引擎的端点占位(容器内同源)
    )
    if not getattr(config, "SPEED8", True):   # A/B 对照: 关掉本轮交付侧改动
        app_src = app_src.replace("resp.set_data(_gzip_cached(body))",
                                  "resp.set_data(_gzip.compress(body, compresslevel=6))")
    _write(build_dir / "app.py", app_src)
    _write(build_dir / "requirements.txt", GENERATED_REQUIREMENTS)
    _write(build_dir / "Dockerfile", GENERATED_DOCKERFILE)
    _write(build_dir / "docker-compose.yml", GENERATED_COMPOSE)
    readme = (
        GENERATED_README
        .replace("@@TASK_ID@@", str(task_id))
        .replace("@@UPSTREAM_ORIGIN@@", upstream_origin)
    )
    _write(build_dir / "README.md", readme)

    run_sh = build_dir / "run.sh"
    _write(run_sh, GENERATED_RUN_SH)
    run_sh.chmod(0o755)
    _write(build_dir / "run.bat", GENERATED_RUN_BAT)
    _write(build_dir / "cache" / ".gitkeep", "")
    _write(build_dir / "logs" / ".gitkeep", "")

    zip_path = config.EXPORTS_DIR / f"{task_id}.zip"
    return build_zip(build_dir, zip_path, f"clone_site_{task_id}")


def directory_tree_text(root: Path, max_lines: int = 400) -> str:
    """生成目录结构树文本(部署蓝图 Tab 展示用)。"""
    if not root.is_dir():
        return "(工程尚未生成)"
    lines = [f"{root.name}/"]
    count = 1

    def walk(directory: Path, prefix: str):
        nonlocal count
        try:
            entries = sorted(directory.iterdir(), key=lambda p: (p.is_file(), p.name.lower()))
        except OSError:
            return
        for idx, entry in enumerate(entries):
            if count >= max_lines:
                lines.append(prefix + "… 更多条目已截断")
                return
            connector = "└── " if idx == len(entries) - 1 else "├── "
            if entry.is_dir():
                lines.append(f"{prefix}{connector}{entry.name}/")
                count += 1
                if entry.name != "__pycache__":
                    walk(entry, prefix + ("    " if idx == len(entries) - 1 else "│   "))
            else:
                try:
                    size = entry.stat().st_size
                    label = f"{entry.name}  ({_fmt_size(size)})"
                except OSError:
                    label = entry.name
                lines.append(f"{prefix}{connector}{label}")
                count += 1

    walk(root, "")
    return "\n".join(lines)


def _fmt_size(num: float) -> str:
    for unit in ("B", "KB", "MB", "GB"):
        if num < 1024 or unit == "GB":
            return f"{num:.1f} {unit}" if unit != "B" else f"{int(num)} B"
        num /= 1024
    return f"{num:.1f} GB"
