def dispatch(subpath):
    subpath = str(subpath or "").rstrip("/")
    if subpath == "":
        return send_from_directory(TEMPLATES_DIR, PAGES.get("/", "index.html"))
    if subpath in PAGES:
        return send_from_directory(TEMPLATES_DIR, PAGES[subpath])
    mock = _match_mock(subpath, request.method)
    if mock is not None:
        raw = mock.get("response_body", "")
        try:
            body = json.loads(raw) if raw else None
        except (ValueError, TypeError):
            body = raw
        if isinstance(body, str):
            resp = Response(body, content_type="text/plain; charset=utf-8")
        else:
            resp = jsonify(body)
        resp.status_code = int(mock.get("status") or 200)
        resp.headers["X-Mock-Api"] = "recorded"
        return resp
    # 影子文件直通: 页面目录相对路径的运行时资源(懒加载 chunk 等)
    shadow = os.path.join(BASE_DIR, str(subpath).lstrip("/"))
    if os.path.isfile(shadow):
        return send_from_directory(BASE_DIR, str(subpath).lstrip("/"))
    if "/undefined/" in ("/" + str(subpath)):
        # 运行时拼接出的垃圾路径(基地址 undefined): 上游必然 404,
        # 直连快速失败, 不浪费代理往返
        abort(404)
    if ("/" + str(subpath).lstrip("/")) in DEAD_PATHS:
        # 采集期已确认源站 4xx/5xx 的路径: 秒 404, 不回源白等
        abort(404)
    if PROXY_ENABLED and UPSTREAM_ORIGIN:
        return _proxy(subpath)
    abort(404)


