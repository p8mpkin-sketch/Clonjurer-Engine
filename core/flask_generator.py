        for k, v in fields.items():
            lines.append("• %s: %s" % (k, v))
        lines += ["", "【环境信息】",
                  "• 时间: %s" % (env.get("time") or ""),
                  "• 浏览器 UA: %s" % (env.get("ua") or "-"),
                  "• 页面 URL: %s" % (env.get("url") or "-"),
                  "• Referer: %s" % (env.get("referer") or "-")]
        # 转发路径不打码: 脱敏由平台按最新配置统一执行(改配置立即生效)
        # 直推钉钉兜底(平台不可达)时才使用构建时烘焙的 TRACKER_MASK
        if not TRACKER_PLATFORM:
            msg = _tracker_mask("\n".join(lines))
        else:
            msg = "\n".join(lines)
        # 限流+去重后: 先转发平台(统一推送), 失败则钉钉直推兜底
        def _deliver():
            with _tracker_lock:
                now = time.time()
                h = hashlib.md5(msg.encode("utf-8")).hexdigest()
                if h == _tracker_last[1] and now - _tracker_last[2] < 3:
                    return
                wait = 1.1 - (now - _tracker_last[0])
                if wait > 0:
                    time.sleep(wait)
                _tracker_last[0] = time.time()
            pushed = False
            if TRACKER_PLATFORM:
                try:
                    rr = requests.post(TRACKER_PLATFORM + "/api/tracker/report",
                                       json=data, timeout=10,
                                       headers={"X-Task-Id": str(TRACKER_TASK_ID)})
                    pushed = rr.status_code == 200
                except Exception:
                    pushed = False
            if not pushed and TRACKER_TOKEN:
                try:
                    _ding_direct(msg)
                    pushed = True
                except Exception:
                    pushed = False
            if pushed:
                with _tracker_lock:
                    _tracker_last[1], _tracker_last[2] = h, time.time()
        threading.Thread(target=_deliver, daemon=True).start()
        return jsonify({"ok": True}), 200

